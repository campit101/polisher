// Copies src/config/usage.ts (the one place usage numbers are edited) into the Edge Functions,
// which Supabase deploys from supabase/functions only. tests/unit/usage-copy.test.ts fails if the
// copy is out of date. Usage: npm run sync:usage
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const USAGE_SOURCE = "src/config/usage.ts";
export const USAGE_COPY = "supabase/functions/_shared/usage.ts";
export const COPY_HEADER = `// GENERATED by npm run sync:usage from ${USAGE_SOURCE}. Edit that file, never this one.\n`;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(USAGE_COPY, COPY_HEADER + readFileSync(USAGE_SOURCE, "utf8"));
  process.stdout.write(`Copied ${USAGE_SOURCE} to ${USAGE_COPY}\n`);
}
